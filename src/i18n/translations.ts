export function getLanguageOption(code: string): LanguageOption {
  return WORLD_LANGUAGES.find((l) => l.code === code) || WORLD_LANGUAGES[0];
}

export function translate(langCode: string, key: string): string {
  const dict = TRANSLATIONS[langCode] || EN;
  return dict[key] ?? EN[key] ?? key;
}

export function detectInitialLanguage(): string {
  if (typeof navigator === 'undefined') return 'en';
  const base = (navigator.language || 'en').split('-')[0].toLowerCase();
  return WORLD_LANGUAGES.some((l) => l.code === base) ? base : 'en';
}
